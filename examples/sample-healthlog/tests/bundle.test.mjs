// Static checks of the shipped bundle: manifest, release.json, knowledge coverage, sandbox rules.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { cpSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { describe, test } from "node:test";
import { fileURLToPath } from "node:url";
import { resolveManifest, validateManifest } from "@tinycloud/node-sdk";
import { okf } from "../scripts/knowledge.mjs";
import { buildRelease } from "../scripts/make-release.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(ROOT, p), "utf8");
const manifest = JSON.parse(read("manifest.json"));
const walk = (dir) => readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]));

describe("manifest", () => {
  test("is a valid TinyCloud manifest with the interop-spec fields", () => {
    validateManifest(manifest);
    assert.equal(manifest.app_id, "xyz.tinycloud.sample.healthlog");
    assert.equal(manifest.knowledge, "knowledge/index.md");
    assert.equal("forked_from" in manifest, false, "an original app carries no forked_from (kit schema: only copies do)");
    assert.equal(manifest.defaults, false);
    assert.equal(manifest.space, "applications");
  });

  test("grants exactly the app's own prefixes; the app cannot write its own code", () => {
    const grants = resolveManifest(manifest).resources
      .filter((r) => r.service !== "tinycloud.capabilities")
      .map((r) => `${r.service} ${r.path} ${r.actions.map((a) => a.split("/")[1]).join(",")}`);
    assert.deepEqual(grants, [
      "tinycloud.sql xyz.tinycloud.sample.healthlog/healthlog read,write,schema",
      "tinycloud.kv xyz.tinycloud.sample.healthlog/prefs/ get,put,del,list",
      "tinycloud.kv xyz.tinycloud.sample.healthlog/app/ get,list",
      "tinycloud.kv xyz.tinycloud.sample.healthlog/knowledge/ get,put,list",
    ]);
  });
});

describe("release.json", () => {
  test("lists every shipped file with its current sha256 and a matching digest", () => {
    const release = JSON.parse(read("release.json"));
    assert.deepEqual(release, buildRelease(), "release.json is stale: run `npm run release`");
    for (const f of release.files) {
      assert.equal(createHash("sha256").update(readFileSync(join(ROOT, f.path))).digest("hex"), f.sha256, f.path);
    }
    const paths = release.files.map((f) => f.path);
    for (const must of ["manifest.json", "schema.sql", "app.jsx", "knowledge/index.md", "knowledge/app.md", "knowledge/log.md"]) {
      assert.ok(paths.includes(must), `${must} missing from release.json`);
    }
    assert.ok(!paths.some((p) => /^(dev|tests|scripts|node_modules)\//.test(p)), "dev files must not ship");
  });
});

describe("knowledge bundle (generated by the app-kit's okf.mjs)", () => {
  test("okf.mjs check knowledge --manifest manifest.json passes", () => {
    const r = okf(["check", "knowledge", "--manifest", "manifest.json"]);
    assert.equal(r.status, 0, `${r.stdout}${r.stderr}`);
  });

  test("knowledge/ matches what the generator produces from manifest + schema.sql + knowledge-src (no drift)", () => {
    const tmp = mkdtempSync(join(tmpdir(), "t2b-okf-"));
    try {
      cpSync(join(ROOT, "knowledge"), join(tmp, "knowledge"), { recursive: true });
      const r = okf(["generate", "manifest.json", "--sql", "schema.sql", "--src", "knowledge-src", "--out", join(tmp, "knowledge"), "--date", "2026-10-20"]);
      assert.equal(r.status, 0, `${r.stdout}${r.stderr}`);
      const changed = walk(join(tmp, "knowledge"))
        .map((p) => relative(join(tmp, "knowledge"), p))
        .filter((f) => f !== "log.md" && readFileSync(join(tmp, "knowledge", f), "utf8") !== read(`knowledge/${f}`));
      assert.deepEqual(changed, [], "knowledge/ is stale: run `npm run knowledge`");
    } finally {
      rmSync(tmp, { recursive: true, force: true });
    }
  });

  test("layout: one concept per table, view and KV permission prefix; resource in tinycloud.<service>:<space>:<path> form", () => {
    const sqlObjects = [...read("schema.sql").matchAll(/CREATE (TABLE|VIEW) IF NOT EXISTS (\w+)/g)].map((m) => [m[1], m[2]]);
    assert.equal(sqlObjects.length, 4);
    const type = (f) => /^type: "?([^"\n]+)"?$/m.exec(read(f))?.[1];
    const resource = (f) => /^resource: (\S+)$/m.exec(read(f))?.[1];
    for (const [kind, name] of sqlObjects) {
      const f = `knowledge/${kind === "TABLE" ? "tables" : "views"}/${name}.md`;
      assert.equal(type(f), kind === "TABLE" ? "SQLite Table" : "SQLite View");
      assert.equal(resource(f), "tinycloud.sql:applications:xyz.tinycloud.sample.healthlog/healthlog");
    }
    const prefixes = manifest.permissions.filter((p) => p.service === "tinycloud.kv").map((p) => p.path);
    assert.deepEqual([...prefixes].sort(), ["app/", "knowledge/", "prefs/"]);
    for (const p of prefixes) {
      const f = `knowledge/kv/${p.replace(/\/$/, "")}.md`;
      assert.equal(type(f), "KV Prefix");
      assert.equal(resource(f), `tinycloud.kv:applications:${manifest.app_id}/${p}`);
    }
    assert.equal(type("knowledge/app.md"), "TinyCloud App");
    assert.match(read("knowledge/index.md"), /^---\nokf_version: "0\.2"\n---\n/);
  });
});

describe("sandbox rules for app.jsx", () => {
  const src = read("app.jsx");
  test("imports only react, recharts and the bridge", () => {
    const specs = [...src.matchAll(/^\s*(?:import|\}\s*from)\s.*?from\s+"([^"]+)"|^\} from "([^"]+)"/gm)].map((m) => m[1] ?? m[2]);
    assert.deepEqual([...new Set(specs)].sort(), ["@tinycloud/app", "react", "recharts"]);
    assert.ok(!/\bimport\s*\(/.test(src), "no dynamic import");
  });

  test("no network, eval, storage, cookies or direct DOM escape hatches", () => {
    const banned = ["fetch(", "XMLHttpRequest", "WebSocket", "EventSource", "sendBeacon", "eval(", "new Function", "Function(", "localStorage", "sessionStorage", "indexedDB", "document.cookie", "importScripts", "postMessage", "window.parent", "window.top", "dangerouslySetInnerHTML", "innerHTML", "<script", "<iframe", "navigator.serviceWorker"];
    for (const b of banned) assert.ok(!src.includes(b), `app.jsx must not use ${b}`);
  });
});
